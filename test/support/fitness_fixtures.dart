/// Builds a completed [WorkoutSession] for tests.
WorkoutSession testSession({
  int id = 1,
  String name = 'Session',
  int type = 0,
  required DateTime startedAt,
  DateTime? endedAt,
  int durationSec = 0,
  int distanceMeters = 0,
}) => WorkoutSession(
  id: id,
  name: name,
  type: type,
  startedAt: startedAt,
  endedAt: endedAt ?? startedAt.add(Duration(seconds: durationSec)),
  durationSec: durationSec,
  distanceMeters: distanceMeters,
  avgPaceSecPerKm: 0,
  calories: 0,
  notes: '',
  routeJson: '',
  planId: null,
  scheduledId: null,
  outcome: 0,
  stepIndex: 0,
  totalSteps: 0,
);
