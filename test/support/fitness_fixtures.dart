  id: id,
  name: name,
  category: category,
  exerciseType: exerciseType,
  targetMuscles: targetMuscles,
  equipment: equipment,
  difficulty: difficulty,
  instructions: '',
  safetyNotes: '',
  formTips: '',
  commonMistakes: '',
  contraindications: '',
  easierAltId: null,
  harderAltId: null,
  demoAsset: '',
  nameKey: '',
  instructionsKey: '',
  safetyNotesKey: '',
  isCustom: false,
  isTimed: isTimed,
  defaultSets: defaultSets,
  defaultReps: defaultReps,
  defaultDurationSec: defaultDurationSec,
  restSec: restSec,
  mediaPath: '',
  sourceId: '',
  slug: '',
  bodyPart: '',
  secondaryMuscles: '',
  sourceCategory: '',
  gifUrl: '',
);

/// Builds a [WorkoutPlanItem] for tests.
WorkoutPlanItem testPlanItem({
  int id = 1,
  int planId = 1,
  int exerciseId = 1,
  int orderIndex = 0,
  int sets = 3,
  int reps = 10,
